#           $1 (optional) - path to the log file. Default:
#           <project>/logs/Didarova_Medina_system_report.log
# =====================================================================

STUDENT_NAME="Didarova Medina"
STUDENT_ID="37944"
STUDENT_GROUP="IT2-2313"

# Directory where this script is located -> project root is one level up
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
LOG_FILE="${1:-$PROJECT_DIR/logs/Didarova_Medina_system_report.log}"

mkdir -p "$(dirname "$LOG_FILE")"

# Everything inside { } is printed to the screen AND appended (tee -a = >>) to the log
{
  echo "=================================================================="
  echo " SYSTEM REPORT - DevOps Midterm"
  echo "=================================================================="
  echo "Student full name : $STUDENT_NAME"
  echo "Student ID        : $STUDENT_ID"
  echo "Group             : $STUDENT_GROUP"
  echo "Date and time     : $(date '+%Y-%m-%d %H:%M:%S %Z')"
  echo "Current user      : $(whoami)"
  echo "Hostname          : $(hostname)"
  echo

  echo "---------------- Operating system and kernel ---------------------"
  if [ -f /etc/os-release ]; then
    . /etc/os-release
    echo "OS                : $PRETTY_NAME"
  else
    echo "OS                : $(uname -s)"
  fi
  echo "Kernel            : $(uname -r)"
  echo "Architecture      : $(uname -m)"
  echo

  echo "---------------- CPU information ---------------------------------"
  if command -v lscpu >/dev/null 2>&1; then
    lscpu | grep -E '^(Model name|CPU\(s\)|Thread\(s\) per core|Architecture)'
  else
    grep -m1 'model name' /proc/cpuinfo
    echo "CPU(s): $(nproc)"
  fi
  echo "Load average      : $(cut -d ' ' -f1-3 /proc/loadavg)"
  echo

  echo "---------------- Memory information ------------------------------"
  free -h
  echo

  echo "---------------- Disk usage --------------------------------------"
  df -h -l -x tmpfs -x devtmpfs -x overlay -x squashfs 2>/dev/null | grep -v ' /opt/' || df -h
  echo

  echo "---------------- Available disk space (/) ------------------------"
  echo "Available on /    : $(df -h / | awk 'NR==2 {print $4}') of $(df -h / | awk 'NR==2 {print $2}') (used $(df -h / | awk 'NR==2 {print $5}'))"
  echo "Project dir size  : $(du -sh "$PROJECT_DIR" 2>/dev/null | cut -f1)"
  echo
  echo "Report generated by $STUDENT_NAME (Didarova)"
  echo "=================================================================="
  echo
} | tee -a "$LOG_FILE"

echo "Report saved to: $LOG_FILE"
